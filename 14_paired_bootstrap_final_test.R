# ============================================================
# SCRIPT 14
# PAIRED BOOTSTRAP OF FINAL HELD-OUT TEST PREDICTIONS
# ============================================================
#
# PURPOSE
#
# Quantify uncertainty in the final held-out TEST performance
# of the seven frozen workflows:
#
# 1. MLR
# 2. PR
# 3. SVR-Linear
# 4. SVR-Polynomial
# 5. SVR-RBF
# 6. RF
# 7. XGB
#
# IMPORTANT
#
# - No model is fitted in this script.
# - No hyperparameter is changed.
# - No variable selection is performed.
# - No transformation decision is performed.
# - Raw TRAIN and TEST datasets are NOT read.
#
# The script uses only the fixed final TEST predictions
# generated by Script 13.
#
# BOOTSTRAP DESIGN
#
# - Nonparametric bootstrap of TEST participants.
# - 2000 valid bootstrap replicates per sex.
# - Sampling with replacement.
# - Sample size remains equal to original TEST size.
# - The SAME resampled participant indices are used for all
#   seven models within each bootstrap replicate.
# - Therefore all model comparisons are paired.
#
# CONFIDENCE INTERVALS
#
# - Percentile bootstrap 95% CI.
# - 2.5th and 97.5th percentiles.
#
# METRICS
#
# RMSE
# MAE
# Predictive R2 = 1 - SSE/SST
#
# PAIRWISE DIFFERENCE
#
# Difference = Model_A - Model_B
#
# RMSE / MAE:
#   negative difference favors Model_A
#
# Predictive R2:
#   positive difference favors Model_A
#
# Pairwise comparisons are exploratory and unadjusted for
# multiplicity.
#
# ============================================================


