      dplyr::filter(
        Model ==
          model_b
      )
    
    
    pair_bootstrap <- sex_pairwise %>%
      
      dplyr::filter(
        Model_A ==
          model_a,
        Model_B ==
          model_b
      )
    
    
    metric_mapping <- data.frame(
      
      Metric = c(
        "RMSE",
        "MAE",
        "Predictive_R2"
      ),
      
      Difference_Column = c(
        "RMSE_Difference",
        "MAE_Difference",
        "R2_Difference"
      ),
      
      stringsAsFactors =
        FALSE
    )
    
    
    for (
      metric_index in
      seq_len(
        nrow(
          metric_mapping
        )
      )
    ) {
      
      metric_name <-
        metric_mapping$Metric[
          metric_index
        ]
      
      
      difference_column <-
        metric_mapping$Difference_Column[
          metric_index
        ]
      
      
      bootstrap_differences <- pair_bootstrap[
        ,
        difference_column,
        drop = TRUE
      ]
      
      
      percentile_ci <- stats::quantile(
        
        bootstrap_differences,
        
        probs = c(
          lower_probability,
          upper_probability
        ),
        
        na.rm =
          TRUE,
        
        names =
          FALSE,
        
        type =
          7
      )
      
      
      point_difference <-
        
        point_a[
          ,
          metric_name,
          drop = TRUE
        ] -
        
        point_b[
          ,
          metric_name,
          drop = TRUE
        ]
      
      
      ci_excludes_zero <-
        (
          percentile_ci[1] > 0
        ) ||
        (
          percentile_ci[2] < 0
        )
      
      
      if (
        !ci_excludes_zero
      ) {
        
        favored_model <-
          "No clear difference"
        
        
      } else if (
        metric_name %in%
        c(
          "RMSE",
          "MAE"
        )
      ) {
        
        # Lower RMSE/MAE is favorable.
        
        if (
          percentile_ci[2] < 0
        ) {
          
          favored_model <-
            model_a
          
        } else {
          
          favored_model <-
            model_b
        }
        
        
      } else {
        
        # Higher predictive R2 is favorable.
        
        if (
          percentile_ci[1] > 0
        ) {
          
          favored_model <-
            model_a
          
        } else {
          
          favored_model <-
            model_b
        }
      }
      
      
      pairwise_summary_rows <- append(
        
        pairwise_summary_rows,
        
        list(
          
          data.frame(
            
            Sex =
              sex_name,
            
            Model_A =
              model_a,
            
            Model_B =
              model_b,
            
            Metric =
              metric_name,
            
            Difference_Definition =
              "Model_A - Model_B",
            
            Point_Difference =
              point_difference,
            
            Bootstrap_Mean_Difference =
              mean(
                bootstrap_differences
              ),
            
            CI_Lower_95 =
              percentile_ci[1],
            
            CI_Upper_95 =
              percentile_ci[2],
            
            CI_Excludes_Zero =
              ci_excludes_zero,
            
            Favored_Model_If_Clear =
              favored_model,
            
            Interpretation =
              ifelse(
                metric_name %in%
                  c(
                    "RMSE",
                    "MAE"
                  ),
                "Lower is better",
                "Higher is better"
              ),
            
            Multiple_Comparison_Adjustment =
              "None; exploratory",
            
            stringsAsFactors =
              FALSE
          )
        )
      )
    }
  }
}


pairwise_difference_cis <-
  dplyr::bind_rows(
