# ============================================================
# 9. METRIC FUNCTIONS
# ============================================================

calculate_rmse <- function(
    observed,
    predicted
) {
  
  sqrt(
    mean(
      (observed - predicted)^2
    )
  )
}


calculate_mae <- function(
    observed,
    predicted
) {
  
  mean(
    abs(
      observed - predicted
    )
  )
}


calculate_predictive_r2 <- function(
    observed,
    predicted
) {
  
  sse <- sum(
    (observed - predicted)^2
  )
  
  
  sst <- sum(
    (observed - mean(observed))^2
  )
  
  
  if (
    !is.finite(sst) ||
    sst <= 0
  ) {
    
    return(
      NA_real_
    )
  }
  
  
  return(
    1 -
      sse /
      sst
  )
}


# ============================================================
# 10. POINT ESTIMATES FROM FIXED TEST PREDICTIONS
# ============================================================

calculate_point_metrics <- function(
    prediction_table,
    sex_name
) {
  
  observed <-
    prediction_table$Observed_HCY
  
  
  result_list <- list()
  
  
  for (
    model_name in
    model_names
  ) {
    
    predicted <- prediction_table[
      ,
      model_name,
      drop = TRUE
    ]
    
    
    result_list <- append(
      
      result_list,
      
      list(
        
        data.frame(
          
          Sex =
            sex_name,
          
          Model =
            model_name,
          
          N =
            length(
              observed
            ),
          
          RMSE =
            calculate_rmse(
              observed,
              predicted
            ),
          
          MAE =
            calculate_mae(
              observed,
              predicted
            ),
          
          Predictive_R2 =
            calculate_predictive_r2(
              observed,
              predicted
            ),
          
          stringsAsFactors =
            FALSE
        )
      )
    )
  }
  
  
  return(
    
    dplyr::bind_rows(
      result_list
    )
  )
}


