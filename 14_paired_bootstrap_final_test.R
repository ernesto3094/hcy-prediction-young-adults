# ============================================================
# 12. PAIRED BOOTSTRAP FUNCTION
#
# The same sampled participant indices are used for every
# model in a given bootstrap replicate.
# ============================================================

run_paired_bootstrap <- function(
    prediction_table,
    sex_name,
    number_replicates
) {
  
  observed <-
    prediction_table$Observed_HCY
  
  
  prediction_matrix <- as.matrix(
    
    prediction_table[
      ,
      model_names,
      drop = FALSE
    ]
  )
  
  
  n <-
    length(
      observed
    )
  
  
  metric_rows <- vector(
    "list",
    number_replicates
  )
  
  
  bootstrap_indices <- matrix(
    
    NA_integer_,
    
    nrow =
      number_replicates,
    
    ncol =
      n
  )
  
  
  valid_replicates <-
    0
  
  
  attempted_replicates <-
    0
  
  
  while (
    valid_replicates <
    number_replicates
  ) {
    
    attempted_replicates <-
      attempted_replicates +
      1
    
    
    sampled_indices <- sample.int(
      
      n =
        n,
      
      size =
        n,
      
      replace =
        TRUE
    )
    
    
    bootstrap_observed <- observed[
      sampled_indices
    ]
    
    
    bootstrap_sst <- sum(
      
      (
        bootstrap_observed -
          mean(
            bootstrap_observed
          )
      )^2
    )
    
    
    # Predictive R2 is undefined if outcome variance is zero.
    # Such a replicate is skipped and replaced.
    
    if (
      !is.finite(
        bootstrap_sst
      ) ||
      bootstrap_sst <= 0
    ) {
      
      next
    }
    
    
    valid_replicates <-
      valid_replicates +
      1
    
    
    bootstrap_indices[
      valid_replicates,
    ] <- sampled_indices
    
    
    replicate_rows <-
      list()
    
    
    for (
      model_name in
      model_names
    ) {
      
      predicted <- prediction_matrix[
        sampled_indices,
        model_name
      ]
      
      
      replicate_rows <- append(
        
        replicate_rows,
        
        list(
          
          data.frame(
            
            Sex =
              sex_name,
            
            Replicate =
              valid_replicates,
            
            Model =
              model_name,
            
            RMSE =
              calculate_rmse(
                bootstrap_observed,
                predicted
              ),
            
            MAE =
              calculate_mae(
                bootstrap_observed,
                predicted
              ),
            
            Predictive_R2 =
              calculate_predictive_r2(
                bootstrap_observed,
                predicted
              ),
            
            stringsAsFactors =
              FALSE
          )
        )
      )
    }
    
    
    metric_rows[
      valid_replicates
    ] <- list(
      
      dplyr::bind_rows(
        replicate_rows
      )
    )
    
    
    if (
      valid_replicates %% 250 ==
      0
    ) {
      
      cat(
        sex_name,
        "- completed",
        valid_replicates,
        "of",
        number_replicates,
        "valid bootstrap replicates.\n"
      )
    }
  }
  
  
  index_table <- as.data.frame(
    bootstrap_indices
  )
  
  
  names(
    index_table
  ) <- paste0(
    "Draw_",
    seq_len(n)
  )
  
  
  index_table$Sex <-
    sex_name
  
  
  index_table$Replicate <-
    seq_len(
      number_replicates
    )
  
  
  index_table <- index_table[
    ,
    c(
      "Sex",
      "Replicate",
      paste0(
        "Draw_",
        seq_len(n)
      )
    )
  ]
  
  
  return(
    
    list(
      
      metrics =
        dplyr::bind_rows(
          metric_rows
        ),
      
      indices =
        index_table,
      
      attempts =
        attempted_replicates
    )
  )
}


