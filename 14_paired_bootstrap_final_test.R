validate_prediction_table <- function(
    data,
    expected_n,
    sex_name
) {
  
  required_columns <- c(
    "ID",
    "Observed_HCY",
    model_names
  )
  
  
  missing_columns <- setdiff(
    required_columns,
    names(data)
  )
  
  
  if (
    length(
      missing_columns
    ) > 0
  ) {
    
    stop(
      paste(
        sex_name,
        "prediction table is missing:",
        paste(
          missing_columns,
          collapse = ", "
        )
      )
    )
  }
  
  
  if (
    nrow(data) !=
    expected_n
  ) {
    
    stop(
      paste(
        sex_name,
        "prediction table has",
        nrow(data),
        "rows; expected",
        expected_n
      )
    )
  }
  
  
  if (
    any(
      duplicated(
        as.character(
          data$ID
        )
      )
    )
  ) {
    
    stop(
      paste(
        "Duplicated TEST IDs detected in",
        sex_name
      )
    )
  }
  
  
  numeric_columns <- c(
    "Observed_HCY",
    model_names
  )
  
  
  for (
    variable in
    numeric_columns
  ) {
    
    values <- data[
      ,
      variable,
      drop = TRUE
    ]
    
    
    if (
      !is.numeric(
        values
      )
    ) {
      
      stop(
        paste(
          sex_name,
          variable,
          "is not numeric."
        )
      )
    }
    
    
    if (
      any(
        is.na(
          values
        )
      )
    ) {
      
      stop(
        paste(
          sex_name,
          variable,
          "contains missing values."
        )
      )
    }
    
    
    if (
      any(
        !is.finite(
          values
        )
      )
    ) {
      
      stop(
        paste(
          sex_name,
          variable,
          "contains non-finite values."
        )
      )
    }
  }
  
  
  invisible(TRUE)
}


